module abro_state_machine(
    input clk,
    input rst_n,
    input A,
    input B,
    output O,
    output [3:0] State
);
    // One-hot state encoding
    localparam [3:0] STATE_A = 4'b0001; // no progress
    localparam [3:0] STATE_B = 4'b0010; // have seen 'A'
    localparam [3:0] STATE_R = 4'b0100; // have seen 'AB'
    localparam [3:0] STATE_O = 4'b1000; // have seen 'ABR'

    reg [3:0] state_reg, state_next;

    // State register (reset to STATE_A)
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            state_reg <= STATE_A;
        else
            state_reg <= state_next;
    end

    // Input symbols
    wire sym_A = A & ~B; // 10  -> corresponds to letter A
    wire sym_B = ~A & B; // 01  -> corresponds to letter B
    wire sym_R = ~A & ~B; // 00  -> corresponds to letter R
    wire sym_O = A & B;   // 11  -> corresponds to letter O

    // Next-state logic (Mealy FSM)
    always @* begin
        // Default: hold current state
        state_next = state_reg;

        case (state_reg)
            STATE_A: begin
                if (sym_A) state_next = STATE_B;
                else if (sym_B) state_next = STATE_A;
                else if (sym_R) state_next = STATE_A;
                else if (sym_O) state_next = STATE_A;
            end
            STATE_B: begin
                if (sym_A) state_next = STATE_B;
                else if (sym_B) state_next = STATE_R;
                else if (sym_R) state_next = STATE_A;
                else if (sym_O) state_next = STATE_A;
            end
            STATE_R: begin
                if (sym_A) state_next = STATE_B;
                else if (sym_B) state_next = STATE_A;
                else if (sym_R) state_next = STATE_O;
                else if (sym_O) state_next = STATE_A;
            end
            STATE_O: begin
                if (sym_A) state_next = STATE_B;
                else if (sym_B) state_next = STATE_A;
                else if (sym_R) state_next = STATE_A;
                else if (sym_O) begin
                    state_next = STATE_A;
                    // Output O will be generated by the Mealy logic below
                end
            end
        endcase
    end

    // Mealy output: high only when we are in STATE_O and the current input is sym_O
    assign O = (state_reg == STATE_O) & sym_O;

    // Output current state for verification (one-hot)
    assign State = state_reg;
endmodule
